import { expect, test } from '@playwright/test'

test('ShopLite icon, responsive workspaces and theme controls', async ({ page, request }) => {
  const errors: string[] = []
  page.on('pageerror', (error) => errors.push(error.message))
  page.on('console', (message) => { if (message.type() === 'error') errors.push(message.text()) })
  await page.emulateMedia({ colorScheme: 'light' })
  await page.goto('/pos')
  await expect(page).toHaveTitle('ShopLite | Quầy thu ngân')
  const brand = page.getByRole('link', { name: 'ShopLite' })
  const icon = brand.locator('img')
  await expect(icon).toBeVisible()
  await expect.poll(() => icon.evaluate((img: HTMLImageElement) => img.naturalWidth)).toBeGreaterThan(0)
  const favicon = await page.locator('link[rel="icon"]').getAttribute('href')
  const response = await request.get(favicon!)
  expect(response.ok()).toBeTruthy()
  expect(response.headers()['content-type']).toContain('image/svg+xml')

  const toggle = page.getByRole('button', { name: 'Giao diện tối' })
  await expect(toggle).toHaveAttribute('aria-pressed', 'false')
  await page.keyboard.press('Tab')
  await expect(brand).toBeFocused()
  await page.keyboard.press('Tab')
  await expect(toggle).toBeFocused()
  await page.keyboard.press('Space')
  await expect(toggle).toHaveAttribute('aria-pressed', 'true')
  await page.reload()
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark')
  const darkSurface = await page.locator('#checkout-panel').evaluate((panel) => getComputedStyle(panel).backgroundColor)

  await expect(page.getByRole('searchbox')).toBeVisible()
  for (const [width, columns] of [[320, 1], [390, 1], [768, 2], [1099, 2], [1100, 3], [1440, 3]]) {
    await page.setViewportSize({ width, height: 900 })
    expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(width)
    expect(await page.locator('.workspace').evaluate((el) => getComputedStyle(el).gridTemplateColumns.split(' ').length)).toBe(columns)
  }

  await page.setViewportSize({ width: 320, height: 720 })
  const nav = page.getByRole('navigation')
  for (const [label, fragment] of [['Sản phẩm', 'catalog-panel'], ['Giỏ hàng', 'cart-panel'], ['Thanh toán', 'checkout-panel']]) {
    await nav.getByRole('link', { name: label, exact: true }).click()
    await expect(page).toHaveURL(new RegExp(`#${fragment}$`))
    await expect(page.locator(`#${fragment}`)).toBeFocused()
  }
  await icon.click()
  await expect(page).toHaveURL(/\/pos$/)
  await toggle.click()
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'light')
  expect(await page.locator('#checkout-panel').evaluate((panel) => getComputedStyle(panel).backgroundColor)).not.toBe(darkSurface)
  expect(errors).toEqual([])
})

test('product artwork, category filters and clear-cart use the live catalog', async ({ page }) => {
  await page.goto('/pos')
  const catalog = page.locator('#catalog')
  const cards = catalog.getByRole('listitem')
  await expect(cards).toHaveCount(8)
  await expect.poll(() => catalog.locator('.product-media').evaluateAll((images) =>
    images.every((image) => (image as HTMLImageElement).naturalWidth > 0))).toBe(true)
  const filters = catalog.getByRole('group', { name: 'Danh mục sản phẩm' })
  await filters.getByRole('button', { name: 'Đồ uống' }).click()
  await expect(cards).toHaveCount(3)
  await filters.getByRole('button', { name: 'Thực phẩm khô' }).click()
  await expect(cards).toHaveCount(2)
  await expect(cards.filter({ hasText: 'Bánh gạo' })).toBeVisible()
  const search = catalog.getByRole('searchbox')
  await search.fill('không có mặt hàng này')
  await expect(catalog.getByText('Không tìm thấy sản phẩm.')).toBeVisible()
  await catalog.getByRole('button', { name: 'Xóa bộ lọc' }).click()
  await expect(search).toBeFocused()
  await expect(search).toHaveValue('')
  await expect(cards).toHaveCount(8)
  await catalog.getByRole('button', { name: 'Thêm vào giỏ: Bánh gạo' }).click()
  await expect.poll(() => page.locator('#cart .thumb').evaluate((img: HTMLImageElement) => img.naturalWidth)).toBeGreaterThan(0)
  await filters.getByRole('button', { name: 'Tất cả' }).click()
  await catalog.getByRole('button', { name: 'Thêm vào giỏ: Cà phê rang xay' }).click()
  await page.getByRole('button', { name: 'Xóa giỏ', exact: true }).click()
  await expect(page.getByText('Chưa có sản phẩm trong giỏ.')).toBeVisible()
  await expect(page.locator('#checkout .total dd')).toContainText(/^0/)
})

test('a new demo product can be found and paid for at its catalog price', async ({ page }) => {
  await page.goto('/pos')
  await page.getByRole('searchbox', { name: 'Tìm sản phẩm' }).fill('TRU-008')
  await page.getByRole('button', { name: 'Thêm vào giỏ: Trứng gà hộp 10 quả' }).click()
  await page.getByRole('radio', { name: 'Tiền mặt' }).check()
  await page.getByRole('textbox', { name: 'Tiền khách đưa (₫)' }).fill('50000')
  await page.getByRole('button', { name: 'Xác nhận thanh toán' }).click()
  await expect(page.getByRole('heading', { name: 'Thanh toán thành công' })).toBeVisible()
  const receipt = page.locator('#checkout .receipt')
  await expect(receipt).toContainText('42.000')
  await expect(receipt).toContainText('8.000')
})
